#!/bin/sh

CONFIG="$1"

[ -z "$CONFIG" ] && CONFIG=".config"

sed -i \
-e 's/^CONFIG_NET_SCH_CAKE=.*/CONFIG_NET_SCH_CAKE=y/' \
-e 's/^CONFIG_NET_SCH_CODEL=.*/CONFIG_NET_SCH_CODEL=y/' \
-e 's/^CONFIG_NET_SCH_FQ_CODEL=.*/CONFIG_NET_SCH_FQ_CODEL=y/' \
-e 's/^# CONFIG_NET_CLS_ACT is not set/CONFIG_NET_CLS_ACT=y/' \
-e 's/^CONFIG_NETFILTER_XT_TARGET_DSCP=.*/CONFIG_NETFILTER_XT_TARGET_DSCP=m/' \
-e 's/^CONFIG_NETFILTER_XT_MATCH_DSCP=.*/CONFIG_NETFILTER_XT_MATCH_DSCP=m/' \
"$CONFIG"

grep -q '^CONFIG_NET_SCH_CAKE=y$' "$CONFIG" || echo 'CONFIG_NET_SCH_CAKE=y' >> "$CONFIG"
grep -q '^CONFIG_NET_SCH_CODEL=y$' "$CONFIG" || echo 'CONFIG_NET_SCH_CODEL=y' >> "$CONFIG"
grep -q '^CONFIG_NET_SCH_FQ_CODEL=y$' "$CONFIG" || echo 'CONFIG_NET_SCH_FQ_CODEL=y' >> "$CONFIG"
grep -q '^CONFIG_NET_CLS_ACT=y$' "$CONFIG" || echo 'CONFIG_NET_CLS_ACT=y' >> "$CONFIG"
grep -q '^CONFIG_NETFILTER_XT_TARGET_DSCP=m$' "$CONFIG" || echo 'CONFIG_NETFILTER_XT_TARGET_DSCP=m' >> "$CONFIG"
grep -q '^CONFIG_NETFILTER_XT_MATCH_DSCP=m$' "$CONFIG" || echo 'CONFIG_NETFILTER_XT_MATCH_DSCP=m' >> "$CONFIG"
